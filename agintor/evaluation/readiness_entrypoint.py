from __future__ import annotations

import argparse
import json
import os
import re
import uuid
from collections.abc import Mapping
from pathlib import Path, PurePosixPath
from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field, TypeAdapter, field_validator, model_validator

from ..authority.roles import current_process_role


READINESS_ENTRY_REQUEST_SCHEMA_VERSION = (
    "repo-repair-harness-readiness-entry-request-v1"
)
READINESS_ENTRY_RESULT_SCHEMA_VERSION = (
    "repo-repair-harness-readiness-entry-result-v1"
)
READINESS_ENTRY_ERROR_SCHEMA_VERSION = (
    "repo-repair-harness-readiness-entry-error-v1"
)

_DIGEST_RE = re.compile(r"^[0-9a-f]{64}$")
_IDENTIFIER_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._:-]{0,191}$")
_MAX_REQUEST_BYTES = 64 * 1024 * 1024
_MAX_ARTIFACT_BYTES = 64 * 1024 * 1024
_MAX_TOTAL_ARTIFACT_BYTES = 512 * 1024 * 1024
_PACKET_ROOTS = frozenset(
    {
        "public_release_evidence",
        "controlled_development_and_evaluator_evidence",
    }
)
_READINESS_MANIFEST_PATH = "mvp_readiness_packet.json"


class ReadinessEntryModel(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, use_enum_values=True)


def _portable_relative_path(value: str, field_name: str) -> str:
    normalized = str(value or "").strip().replace("\\", "/")
    path = PurePosixPath(normalized)
    windows_drive = bool(path.parts and re.fullmatch(r"[A-Za-z]:", path.parts[0]))
    if (
        not normalized
        or path.is_absolute()
        or windows_drive
        or normalized == "."
        or ".." in path.parts
    ):
        raise ValueError(f"{field_name} must be a safe controlled-root-relative path")
    return path.as_posix()


def _packet_relative_path(value: str) -> str:
    normalized = _portable_relative_path(value, "packet_path")
    path = PurePosixPath(normalized)
    if not path.parts or path.parts[0] not in _PACKET_ROOTS:
        raise ValueError("packet_path must use a public-release or controlled evidence root")
    if normalized == _READINESS_MANIFEST_PATH:
        raise ValueError("the readiness manifest is generated by the controlled writer")
    return normalized


class ReadinessArtifactSource(ReadinessEntryModel):
    packet_path: str
    source_path: str

    @field_validator("packet_path")
    @classmethod
    def validate_packet_path(cls, value: str) -> str:
        return _packet_relative_path(value)

    @field_validator("source_path")
    @classmethod
    def validate_source_path(cls, value: str) -> str:
        return _portable_relative_path(value, "source_path")


class ReadinessBuildEnvelope(ReadinessEntryModel):
    schema_version: Literal[READINESS_ENTRY_REQUEST_SCHEMA_VERSION] = (
        READINESS_ENTRY_REQUEST_SCHEMA_VERSION
    )
    operation: Literal["build"] = "build"
    packet_id: str
    destination_root: str
    evaluation_contract_source_path: str
    artifacts: tuple[ReadinessArtifactSource, ...] = Field(min_length=1)
    release: dict[str, Any]
    gate0: dict[str, Any]
    d0: dict[str, Any]
    s1: dict[str, Any]
    solve_execution: dict[str, Any]
    task_audit: dict[str, Any]
    pilot_dry_run: dict[str, Any]
    pilot_report: dict[str, Any]
    factory_followup: dict[str, Any]
    runtime_sessions: dict[str, Any]
    limitations: tuple[str, ...] = Field(min_length=1)

    @field_validator("packet_id")
    @classmethod
    def validate_packet_id(cls, value: str) -> str:
        normalized = str(value or "").strip()
        if not _IDENTIFIER_RE.fullmatch(normalized):
            raise ValueError("packet_id must be a portable identifier")
        return normalized

    @field_validator("destination_root", "evaluation_contract_source_path")
    @classmethod
    def validate_controlled_path(cls, value: str, info: Any) -> str:
        return _portable_relative_path(value, info.field_name)

    @field_validator("limitations")
    @classmethod
    def validate_limitations(cls, value: tuple[str, ...]) -> tuple[str, ...]:
        normalized = tuple(str(item or "").strip() for item in value)
        if any(not item or "\x00" in item or "\r" in item for item in normalized):
            raise ValueError("readiness limitations must be nonempty canonical text")
        return normalized

    @model_validator(mode="after")
    def validate_artifact_map(self) -> "ReadinessBuildEnvelope":
        packet_paths = [item.packet_path for item in self.artifacts]
        source_paths = [item.source_path for item in self.artifacts]
        if len(packet_paths) != len(set(packet_paths)):
            raise ValueError("readiness artifact packet paths may not duplicate")
        if len(source_paths) != len(set(source_paths)):
            raise ValueError("readiness artifact source paths may not duplicate")
        if self.evaluation_contract_source_path in source_paths:
            raise ValueError("sealed EvaluationContract may not enter the readiness packet")
        return self


class ReadinessReplayEnvelope(ReadinessEntryModel):
    schema_version: Literal[READINESS_ENTRY_REQUEST_SCHEMA_VERSION] = (
        READINESS_ENTRY_REQUEST_SCHEMA_VERSION
    )
    operation: Literal["replay"] = "replay"
    generation_path: str
    evaluation_contract_source_path: str

    @field_validator("generation_path", "evaluation_contract_source_path")
    @classmethod
    def validate_controlled_path(cls, value: str, info: Any) -> str:
        return _portable_relative_path(value, info.field_name)


ReadinessFileRequest = Annotated[
    ReadinessBuildEnvelope | ReadinessReplayEnvelope,
    Field(discriminator="operation"),
]
_REQUEST_ADAPTER = TypeAdapter(ReadinessFileRequest)


class ReadinessEntrySuccess(ReadinessEntryModel):
    schema_version: Literal[READINESS_ENTRY_RESULT_SCHEMA_VERSION] = (
        READINESS_ENTRY_RESULT_SCHEMA_VERSION
    )
    status: Literal["succeeded"] = "succeeded"
    operation: Literal["build", "replay"]
    live_status: Literal["not_run"] = "not_run"
    inference_requests_sent: Literal[0] = 0
    packet_id: str
    packet_digest: str
    packet_path: str

    @field_validator("packet_id")
    @classmethod
    def validate_packet_id(cls, value: str) -> str:
        normalized = str(value or "").strip()
        if not _IDENTIFIER_RE.fullmatch(normalized):
            raise ValueError("packet_id must be a portable identifier")
        return normalized

    @field_validator("packet_digest")
    @classmethod
    def validate_packet_digest(cls, value: str) -> str:
        normalized = str(value or "").strip().lower()
        if not _DIGEST_RE.fullmatch(normalized):
            raise ValueError("packet_digest must be a lowercase SHA-256 digest")
        return normalized

    @field_validator("packet_path")
    @classmethod
    def validate_packet_path(cls, value: str) -> str:
        return _portable_relative_path(value, "packet_path")


class ReadinessEntryErrorResult(ReadinessEntryModel):
    schema_version: Literal[READINESS_ENTRY_ERROR_SCHEMA_VERSION] = (
        READINESS_ENTRY_ERROR_SCHEMA_VERSION
    )
    status: Literal["failed"] = "failed"
    code: str = Field(min_length=1)
    message: str = Field(min_length=1)


class ReadinessEntryError(RuntimeError):
    def __init__(self, code: str, message: str) -> None:
        self.code = str(code)
        super().__init__(message)


def _require_evaluator_role() -> None:
    try:
        role = current_process_role()
    except RuntimeError as exc:
        raise ReadinessEntryError(
            "process_role_invalid",
            "readiness entrypoint received an unsupported process role",
        ) from exc
    if role != "evaluator":
        raise ReadinessEntryError(
            "evaluator_role_required",
            "readiness entrypoint runs only with AGINTOR_PROCESS_ROLE=evaluator",
        )


def _assert_no_symlink_components(path: Path, *, stop: Path, label: str) -> None:
    current = path
    while True:
        if current.exists() and current.is_symlink():
            raise ReadinessEntryError(
                "controlled_path_invalid",
                f"{label} may not cross a symbolic link",
            )
        if current == stop:
            return
        if current == current.parent:
            raise ReadinessEntryError(
                "controlled_path_invalid",
                f"{label} escaped the controlled root",
            )
        current = current.parent


def _controlled_root(value: str | Path) -> Path:
    candidate = Path(value).expanduser()
    if candidate.is_symlink():
        raise ReadinessEntryError(
            "controlled_root_invalid",
            "readiness controlled root may not be a symbolic link",
        )
    root = candidate.resolve()
    if not root.is_dir():
        raise ReadinessEntryError(
            "controlled_root_invalid",
            "readiness controlled root must be an existing directory",
        )
    return root


def _resolve_controlled_path(
    root: Path,
    relative_path: str,
    *,
    label: str,
    kind: Literal["file", "directory", "destination"],
) -> Path:
    normalized = _portable_relative_path(relative_path, label)
    candidate = root.joinpath(*PurePosixPath(normalized).parts)
    _assert_no_symlink_components(candidate, stop=root, label=label)
    resolved = candidate.resolve()
    if root not in resolved.parents:
        raise ReadinessEntryError(
            "controlled_path_invalid",
            f"{label} escaped the controlled root",
        )
    if kind == "file" and (not resolved.is_file() or resolved.is_symlink()):
        raise ReadinessEntryError(
            "controlled_input_missing",
            f"{label} must be an existing regular file",
        )
    if kind == "directory" and (not resolved.is_dir() or resolved.is_symlink()):
        raise ReadinessEntryError(
            "controlled_input_missing",
            f"{label} must be an existing real directory",
        )
    if kind == "destination" and resolved.exists() and not resolved.is_dir():
        raise ReadinessEntryError(
            "controlled_path_invalid",
            f"{label} must be a directory destination",
        )
    return resolved


def _strict_json_object(path: Path, *, label: str) -> dict[str, Any]:
    def reject_duplicates(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f"duplicate key {key!r}")
            result[key] = value
        return result

    try:
        raw = path.read_bytes()
        if len(raw) > _MAX_REQUEST_BYTES:
            raise ValueError("JSON input exceeds the readiness size limit")
        payload = json.loads(
            raw.decode("utf-8"),
            object_pairs_hook=reject_duplicates,
        )
    except (OSError, UnicodeDecodeError, json.JSONDecodeError, ValueError) as exc:
        raise ReadinessEntryError(
            "readiness_request_invalid",
            f"{label} must be strict UTF-8 JSON",
        ) from exc
    if not isinstance(payload, Mapping):
        raise ReadinessEntryError(
            "readiness_request_invalid",
            f"{label} JSON root must be an object",
        )
    return dict(payload)


def _request_path(root: Path, value: str | Path) -> Path:
    candidate = Path(value).expanduser()
    if not candidate.is_absolute():
        candidate = root / candidate
    _assert_no_symlink_components(candidate, stop=root, label="readiness request")
    request = candidate.resolve()
    if root not in request.parents or not request.is_file() or request.is_symlink():
        raise ReadinessEntryError(
            "readiness_request_path_invalid",
            "readiness request must be a regular file inside the controlled root",
        )
    return request


def _paths_overlap(first: Path, second: Path) -> bool:
    return first == second or first in second.parents or second in first.parents


def _load_canary_authority(root: Path, relative_path: str):
    contract_path = _resolve_controlled_path(
        root,
        relative_path,
        label="sealed EvaluationContract source",
        kind="file",
    )
    try:
        from .contracts import evaluation_canary_digests, load_evaluation_contract

        contract = load_evaluation_contract(contract_path)
    except Exception as exc:
        raise ReadinessEntryError(
            "evaluation_contract_invalid",
            "sealed EvaluationContract failed evaluator-owned validation",
        ) from exc
    return (
        contract_path,
        tuple(canary.value for canary in contract.canaries),
        evaluation_canary_digests(contract),
        contract.evaluation_contract_digest,
    )


def _typed_build_inputs(request: ReadinessBuildEnvelope) -> dict[str, Any]:
    try:
        from ..contracts.run_evidence import assert_no_resolved_credentials
        from .pilot import (
            D0FixtureFeasibilityEvidence,
            FactoryFollowupIdentityEvidence,
            Gate0OfflineReadiness,
            ImmutableReleaseIdentity,
            OfflineSolveExecutionProvenance,
            PilotDryRunManifest,
            PilotNotRunDevelopmentReport,
            PilotTaskAuditManifest,
            RuntimeSessionIdentitySet,
            S1OfflineRetentionEvidence,
        )

        assert_no_resolved_credentials(request.model_dump(mode="json"))
        return {
            "release": ImmutableReleaseIdentity.model_validate(request.release),
            "gate0": Gate0OfflineReadiness.model_validate(request.gate0),
            "d0": D0FixtureFeasibilityEvidence.model_validate(request.d0),
            "s1": S1OfflineRetentionEvidence.model_validate(request.s1),
            "solve_execution": OfflineSolveExecutionProvenance.model_validate(
                request.solve_execution
            ),
            "task_audit": PilotTaskAuditManifest.model_validate(request.task_audit),
            "pilot_dry_run": PilotDryRunManifest.model_validate(request.pilot_dry_run),
            "pilot_report": PilotNotRunDevelopmentReport.model_validate(
                request.pilot_report
            ),
            "factory_followup": FactoryFollowupIdentityEvidence.model_validate(
                request.factory_followup
            ),
            "runtime_sessions": RuntimeSessionIdentitySet.model_validate(
                request.runtime_sessions
            ),
        }
    except Exception as exc:
        if isinstance(exc, ReadinessEntryError):
            raise
        raise ReadinessEntryError(
            "readiness_identity_invalid",
            "readiness typed identity inputs failed strict validation",
        ) from exc


def _load_artifacts(
    root: Path,
    request: ReadinessBuildEnvelope,
    *,
    destination: Path,
    request_path: Path,
    contract_path: Path,
) -> dict[str, bytes]:
    artifacts: dict[str, bytes] = {}
    total_bytes = 0
    for source in request.artifacts:
        source_path = _resolve_controlled_path(
            root,
            source.source_path,
            label=f"readiness artifact source {source.packet_path!r}",
            kind="file",
        )
        if (
            _paths_overlap(destination, source_path)
            or source_path == request_path
            or source_path == contract_path
        ):
            raise ReadinessEntryError(
                "controlled_path_overlap",
                "readiness inputs must remain outside the immutable packet destination",
            )
        size = source_path.stat().st_size
        if size > _MAX_ARTIFACT_BYTES:
            raise ReadinessEntryError(
                "readiness_artifact_too_large",
                "one readiness artifact exceeds the controlled size limit",
            )
        total_bytes += size
        if total_bytes > _MAX_TOTAL_ARTIFACT_BYTES:
            raise ReadinessEntryError(
                "readiness_artifacts_too_large",
                "readiness artifacts exceed the controlled aggregate size limit",
            )
        artifacts[source.packet_path] = source_path.read_bytes()
    return artifacts


def _execute_build(
    root: Path,
    request_path: Path,
    request: ReadinessBuildEnvelope,
) -> ReadinessEntrySuccess:
    destination = _resolve_controlled_path(
        root,
        request.destination_root,
        label="readiness packet destination root",
        kind="destination",
    )
    contract_path, canary_values, canary_digests, contract_digest = (
        _load_canary_authority(
            root,
            request.evaluation_contract_source_path,
        )
    )
    if (
        _paths_overlap(destination, request_path)
        or _paths_overlap(destination, contract_path)
    ):
        raise ReadinessEntryError(
            "controlled_path_overlap",
            "readiness request and sealed authority must remain outside packet generations",
        )
    artifacts = _load_artifacts(
        root,
        request,
        destination=destination,
        request_path=request_path,
        contract_path=contract_path,
    )
    typed = _typed_build_inputs(request)
    if typed["d0"].evaluation_contract_digest != contract_digest or any(
        call.evaluation_contract_digest != contract_digest
        for call in typed["pilot_dry_run"].evaluator_calls
    ):
        raise ReadinessEntryError(
            "evaluation_contract_identity_mismatch",
            "sealed EvaluationContract crossed readiness evaluator identity",
        )
    try:
        from .pilot import (
            build_mvp_readiness_evidence_packet,
            write_mvp_readiness_evidence_packet,
        )

        packet = build_mvp_readiness_evidence_packet(
            packet_id=request.packet_id,
            limitations=request.limitations,
            artifacts=artifacts,
            **typed,
        )
        generation = write_mvp_readiness_evidence_packet(
            destination,
            packet=packet,
            artifacts=artifacts,
            canary_values=canary_values,
            canary_digests=canary_digests,
        )
    except Exception as exc:
        raise ReadinessEntryError(
            "readiness_build_failed",
            "controlled MVP readiness packet build failed validation",
        ) from exc
    relative_generation = generation.relative_to(root).as_posix()
    return ReadinessEntrySuccess(
        operation="build",
        packet_id=packet.packet_id,
        packet_digest=packet.packet_digest,
        packet_path=relative_generation,
    )


def _execute_replay(
    root: Path,
    request_path: Path,
    request: ReadinessReplayEnvelope,
) -> ReadinessEntrySuccess:
    generation = _resolve_controlled_path(
        root,
        request.generation_path,
        label="readiness packet generation",
        kind="directory",
    )
    contract_path, canary_values, canary_digests, contract_digest = (
        _load_canary_authority(
            root,
            request.evaluation_contract_source_path,
        )
    )
    if _paths_overlap(generation, request_path) or _paths_overlap(
        generation,
        contract_path,
    ):
        raise ReadinessEntryError(
            "controlled_path_overlap",
            "readiness replay inputs must remain outside the immutable generation",
        )
    try:
        from .pilot import replay_mvp_readiness_evidence_packet

        packet = replay_mvp_readiness_evidence_packet(
            generation,
            canary_values=canary_values,
            canary_digests=canary_digests,
        )
    except Exception as exc:
        raise ReadinessEntryError(
            "readiness_replay_failed",
            "immutable MVP readiness packet replay failed validation",
        ) from exc
    if packet.d0.evaluation_contract_digest != contract_digest:
        raise ReadinessEntryError(
            "evaluation_contract_identity_mismatch",
            "sealed EvaluationContract crossed immutable packet evaluator identity",
        )
    return ReadinessEntrySuccess(
        operation="replay",
        packet_id=packet.packet_id,
        packet_digest=packet.packet_digest,
        packet_path=generation.relative_to(root).as_posix(),
    )


def execute_readiness_file(
    controlled_root: str | Path,
    request_json: str | Path,
) -> ReadinessEntrySuccess:
    _require_evaluator_role()
    root = _controlled_root(controlled_root)
    request_path = _request_path(root, request_json)
    payload = _strict_json_object(request_path, label="readiness request")
    try:
        request = _REQUEST_ADAPTER.validate_python(payload)
    except Exception as exc:
        raise ReadinessEntryError(
            "readiness_request_invalid",
            "readiness request failed strict discriminated validation",
        ) from exc
    if isinstance(request, ReadinessBuildEnvelope):
        return _execute_build(root, request_path, request)
    return _execute_replay(root, request_path, request)


def _output_path(value: str | Path, *, root: Path, request_path: Path) -> Path:
    candidate = Path(value).expanduser()
    if candidate.is_symlink():
        raise ReadinessEntryError(
            "output_path_invalid",
            "readiness child output may not be a symbolic link",
        )
    output = candidate.resolve()
    if output == request_path or output == root or root in output.parents:
        raise ReadinessEntryError(
            "output_path_invalid",
            "readiness child output must remain outside controlled evidence",
        )
    if output.exists() and not output.is_file():
        raise ReadinessEntryError(
            "output_path_invalid",
            "readiness child output must be a regular file destination",
        )
    return output


def _write_json_atomic(path: Path, payload: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.parent / f".{path.name}.{uuid.uuid4().hex}.tmp"
    try:
        with temporary.open("x", encoding="utf-8", newline="\n") as handle:
            json.dump(dict(payload), handle, ensure_ascii=False, indent=2, sort_keys=True)
            handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def _error_result(exc: Exception) -> ReadinessEntryErrorResult:
    if isinstance(exc, ReadinessEntryError):
        return ReadinessEntryErrorResult(code=exc.code, message=str(exc))
    return ReadinessEntryErrorResult(
        code="readiness_entry_failed",
        message=f"{type(exc).__name__}: controlled readiness operation failed",
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m agintor.evaluation.readiness_entrypoint"
    )
    parser.add_argument("--controlled-root", required=True)
    parser.add_argument("--request-json", required=True)
    parser.add_argument("--output-json", required=True)
    args = parser.parse_args(argv)

    output: Path | None = None
    try:
        root = _controlled_root(args.controlled_root)
        request_path = _request_path(root, args.request_json)
        output = _output_path(args.output_json, root=root, request_path=request_path)
        result = execute_readiness_file(root, request_path)
        _write_json_atomic(output, result.model_dump(mode="json"))
        return 0
    except Exception as exc:
        error = _error_result(exc)
        if output is not None:
            _write_json_atomic(output, error.model_dump(mode="json"))
        return 2


